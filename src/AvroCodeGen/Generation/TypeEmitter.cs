using System.Text;
using Avro;

namespace AvroCodeGen.Generation;

internal sealed class TypeEmitter(Naming naming, TypeMapper types)
{
    private StringBuilder _sb = new();
    private int _indent;
    private int _counter;
    private readonly List<string> _staticFields = [];

    private void Line(string text = "") => _sb.AppendLine(text.Length == 0 ? "" : new string(' ', _indent * 4) + text);
    private void Open(string text) { Line(text); Line("{"); _indent++; }
    private void Close() { _indent--; Line("}"); }
    private string Next() => $"v{++_counter}";

    private void Header(NamedSchema schema)
    {
        _sb = new StringBuilder();
        _indent = 0;
        _counter = 0;
        _staticFields.Clear();
        Line("// <auto-generated>Generated by AvroCodeGen. Do not edit.</auto-generated>");
        Line("#nullable enable");
        Line("#pragma warning disable CS1591");
        Line();
        Line($"namespace {naming.Namespace(schema.Namespace)};");
        Line();
    }

    private void Doc(string? doc)
    {
        if (string.IsNullOrWhiteSpace(doc)) return;
        Line("/// <summary>");
        foreach (var l in doc.Split('\n'))
            Line("/// " + System.Security.SecurityElement.Escape(l.TrimEnd('\r')));
        Line("/// </summary>");
    }

    public string EmitEnum(EnumSchema e)
    {
        Header(e);
        var name = naming.TypeName(e);
        Doc(e.Documentation);
        Open($"public enum {name}");
        foreach (var sym in e.Symbols) Line(Naming.Pascal(sym) + ",");
        Close();
        Line();
        Open($"internal static class {name}Avro");
        Line($"public static readonly string[] Symbols = {SymbolArray(e.Symbols)};");
        Close();
        return _sb.ToString();
    }

    public string EmitFixed(FixedSchema f)
    {
        Header(f);
        var name = naming.TypeName(f);
        Doc(f.Documentation);
        Open($"public sealed record {name}");
        Line($"public const int Size = {f.Size};");
        Line("public required byte[] Value { get; init; }");
        Close();
        return _sb.ToString();
    }

    public string EmitRecord(RecordSchema r)
    {
        Header(r);
        var name = naming.TypeName(r);
        Doc(r.Documentation);
        Open($"public sealed record {name} : global::AvroCodeGen.Runtime.IAvroRecord<{name}>");
        Line($"public static string SchemaJson => {Naming.Literal(r.ToString())};");
        Line();

        var members = r.Fields.Select(f => (Field: f, Prop: Naming.Member(f.Name, name))).ToList();
        foreach (var (f, prop) in members)
        {
            Doc(f.Documentation);
            var type = types.CsType(f.Schema);
            bool optional = type.EndsWith('?');
            Line($"public {(optional ? "" : "required ")}{type} {prop} {{ get; init; }}");
        }
        Line();

        var body = new StringBuilder();
        var savedSb = _sb;
        int savedIndent = _indent;

        _sb = body;
        _indent = 1;
        _counter = 0;
        Open("public void Write(global::AvroCodeGen.Runtime.IAvroWriter w)");
        Line("w.WriteRecordStart();");
        foreach (var (f, prop) in members)
        {
            Line($"w.WriteField({Naming.Literal(f.Name)});");
            EmitWrite(f.Schema, prop);
        }
        Line("w.WriteRecordEnd();");
        Close();
        Line();

        Open($"public static {name} Read(global::AvroCodeGen.Runtime.IAvroReader r)");
        Line("r.ReadRecordStart();");
        var vars = new List<string>();
        foreach (var (f, _) in members)
        {
            Line($"r.ReadField({Naming.Literal(f.Name)});");
            vars.Add(EmitRead(f.Schema));
        }
        Line("r.ReadRecordEnd();");
        Open($"return new {name}");
        for (int i = 0; i < members.Count; i++) Line($"{members[i].Prop} = {vars[i]},");
        _indent--;
        Line("};");
        Close();

        _sb = savedSb;
        _indent = savedIndent;
        foreach (var field in _staticFields) Line(field);
        if (_staticFields.Count > 0) Line();
        _sb.Append(body);
        Close();
        return _sb.ToString();
    }

    private static string SymbolArray(IEnumerable<string> items) =>
        "new[] { " + string.Join(", ", items.Select(Naming.Literal)) + " }";

    private string StaticArray(IEnumerable<string> items)
    {
        var name = $"_names{_staticFields.Count}";
        _staticFields.Add($"private static readonly string[] {name} = {SymbolArray(items)};");
        return name;
    }

    private static string SymbolsRef(Naming n, EnumSchema e) => $"{n.FullTypeName(e)}Avro.Symbols";

    private static string Scale(LogicalSchema l) =>
        (l.GetProperty("scale") ?? l.BaseSchema.GetProperty("scale") ?? "0").Trim('"');

    private static string FixedSize(LogicalSchema l) => l.BaseSchema is FixedSchema f ? $", {f.Size}" : "";

    private void EmitWrite(Schema schema, string expr)
    {
        var s = TypeMapper.Normalize(schema);
        switch (s)
        {
            case LogicalSchema l:
                var call = l.LogicalTypeName switch
                {
                    "decimal" => l.BaseSchema is FixedSchema
                        ? $"w.WriteFixed(global::AvroCodeGen.Runtime.AvroLogical.FromDecimal({expr}, {Scale(l)}{FixedSize(l)}));"
                        : $"w.WriteBytes(global::AvroCodeGen.Runtime.AvroLogical.FromDecimal({expr}, {Scale(l)}));",
                    "uuid" => $"w.WriteString(global::AvroCodeGen.Runtime.AvroLogical.FromUuid({expr}));",
                    "date" => $"w.WriteInt(global::AvroCodeGen.Runtime.AvroLogical.FromDate({expr}));",
                    "time-millis" => $"w.WriteInt(global::AvroCodeGen.Runtime.AvroLogical.FromTimeMillis({expr}));",
                    "time-micros" => $"w.WriteLong(global::AvroCodeGen.Runtime.AvroLogical.FromTimeMicros({expr}));",
                    "timestamp-millis" => $"w.WriteLong(global::AvroCodeGen.Runtime.AvroLogical.FromTimestampMillis({expr}));",
                    _ => $"w.WriteLong(global::AvroCodeGen.Runtime.AvroLogical.FromTimestampMicros({expr}));"
                };
                Line(call);
                break;
            case RecordSchema:
                Line($"{expr}.Write(w);");
                break;
            case EnumSchema e:
                Line($"w.WriteEnum((int){expr}, {SymbolsRef(naming, e)});");
                break;
            case FixedSchema:
                Line($"w.WriteFixed({expr}.Value);");
                break;
            case ArraySchema a:
                var item = Next();
                Line($"w.WriteArrayStart({expr}.Count);");
                Open($"foreach (var {item} in {expr})");
                EmitWrite(a.ItemSchema, item);
                Close();
                Line("w.WriteArrayEnd();");
                break;
            case MapSchema m:
                var kv = Next();
                Line($"w.WriteMapStart({expr}.Count);");
                Open($"foreach (var {kv} in {expr})");
                Line($"w.WriteMapKey({kv}.Key);");
                EmitWrite(m.ValueSchema, $"{kv}.Value");
                Close();
                Line("w.WriteMapEnd();");
                break;
            case UnionSchema u:
                EmitWriteUnion(u, expr);
                break;
            default:
                Line(s.Tag switch
                {
                    Schema.Type.Null => "w.WriteNull();",
                    Schema.Type.Boolean => $"w.WriteBoolean({expr});",
                    Schema.Type.Int => $"w.WriteInt({expr});",
                    Schema.Type.Long => $"w.WriteLong({expr});",
                    Schema.Type.Float => $"w.WriteFloat({expr});",
                    Schema.Type.Double => $"w.WriteDouble({expr});",
                    Schema.Type.Bytes => $"w.WriteBytes({expr});",
                    Schema.Type.String => $"w.WriteString({expr});",
                    _ => throw new NotSupportedException($"Unsupported schema type {s.Tag}.")
                });
                break;
        }
    }

    private void WriteBranch(int index, Schema branch, string expr)
    {
        Line($"w.WriteUnion({index}, {Naming.Literal(TypeMapper.BranchName(branch))});");
        EmitWrite(branch, expr);
        Line("w.WriteUnionEnd();");
    }

    private void EmitWriteUnion(UnionSchema u, string expr)
    {
        var branches = u.Schemas;
        if (TypeMapper.IsNullable(u, out var inner))
        {
            int nullIdx = branches[0].Tag == Schema.Type.Null ? 0 : 1;
            var v = Next();
            Open($"if ({expr} is {{ }} {v})");
            WriteBranch(1 - nullIdx, inner, v);
            Close();
            Open("else");
            WriteBranch(nullIdx, branches[nullIdx], "null");
            Close();
            return;
        }

        for (int i = 0; i < branches.Count; i++)
        {
            var b = TypeMapper.Normalize(branches[i]);
            string cond, target;
            if (b.Tag == Schema.Type.Null) { cond = $"{expr} is null"; target = "null"; }
            else { target = Next(); cond = $"{expr} is {types.CsType(b)} {target}"; }
            Open($"{(i == 0 ? "" : "else ")}if ({cond})");
            WriteBranch(i, branches[i], target);
            Close();
        }
        Open("else");
        Line("throw new global::AvroCodeGen.Runtime.AvroException(\"Value does not match any union branch.\");");
        Close();
    }

    private string EmitRead(Schema schema)
    {
        var s = TypeMapper.Normalize(schema);
        var v = Next();
        const string L = "global::AvroCodeGen.Runtime.AvroLogical";
        switch (s)
        {
            case LogicalSchema l:
                Line(l.LogicalTypeName switch
                {
                    "decimal" => l.BaseSchema is FixedSchema f
                        ? $"var {v} = {L}.ToDecimal(r.ReadFixed({f.Size}), {Scale(l)});"
                        : $"var {v} = {L}.ToDecimal(r.ReadBytes(), {Scale(l)});",
                    "uuid" => $"var {v} = {L}.ToUuid(r.ReadString());",
                    "date" => $"var {v} = {L}.ToDate(r.ReadInt());",
                    "time-millis" => $"var {v} = {L}.ToTimeMillis(r.ReadInt());",
                    "time-micros" => $"var {v} = {L}.ToTimeMicros(r.ReadLong());",
                    "timestamp-millis" => $"var {v} = {L}.ToTimestampMillis(r.ReadLong());",
                    _ => $"var {v} = {L}.ToTimestampMicros(r.ReadLong());"
                });
                break;
            case RecordSchema rec:
                Line($"var {v} = {naming.FullTypeName(rec)}.Read(r);");
                break;
            case EnumSchema e:
                Line($"var {v} = ({naming.FullTypeName(e)})r.ReadEnum({SymbolsRef(naming, e)});");
                break;
            case FixedSchema f:
                Line($"var {v} = new {naming.FullTypeName(f)} {{ Value = r.ReadFixed({f.Size}) }};");
                break;
            case ArraySchema a:
                Line($"var {v} = new global::System.Collections.Generic.List<{types.CsType(a.ItemSchema)}>();");
                Line("r.ReadArrayStart();");
                Open("while (r.NextArrayItem())");
                var item = EmitRead(a.ItemSchema);
                Line($"{v}.Add({item});");
                Close();
                Line("r.ReadArrayEnd();");
                break;
            case MapSchema m:
                Line($"var {v} = new global::System.Collections.Generic.Dictionary<string, {types.CsType(m.ValueSchema)}>();");
                Line("r.ReadMapStart();");
                Open("while (r.NextMapEntry())");
                var key = Next();
                Line($"var {key} = r.ReadMapKey();");
                var val = EmitRead(m.ValueSchema);
                Line($"{v}[{key}] = {val};");
                Close();
                Line("r.ReadMapEnd();");
                break;
            case UnionSchema u:
                EmitReadUnion(u, v);
                break;
            default:
                Line(s.Tag switch
                {
                    Schema.Type.Null => $"r.ReadNull(); object? {v} = null;",
                    Schema.Type.Boolean => $"var {v} = r.ReadBoolean();",
                    Schema.Type.Int => $"var {v} = r.ReadInt();",
                    Schema.Type.Long => $"var {v} = r.ReadLong();",
                    Schema.Type.Float => $"var {v} = r.ReadFloat();",
                    Schema.Type.Double => $"var {v} = r.ReadDouble();",
                    Schema.Type.Bytes => $"var {v} = r.ReadBytes();",
                    Schema.Type.String => $"var {v} = r.ReadString();",
                    _ => throw new NotSupportedException($"Unsupported schema type {s.Tag}.")
                });
                break;
        }
        return v;
    }

    private void EmitReadUnion(UnionSchema u, string v)
    {
        var names = StaticArray(u.Schemas.Select(TypeMapper.BranchName));
        Line($"{types.CsType(u)} {v} = default;");
        Open($"switch (r.ReadUnionIndex({names}))");
        for (int i = 0; i < u.Schemas.Count; i++)
        {
            Line($"case {i}:");
            Line("{");
            _indent++;
            if (u.Schemas[i].Tag == Schema.Type.Null) Line("r.ReadNull();");
            else
            {
                var x = EmitRead(u.Schemas[i]);
                Line($"{v} = {x};");
            }
            Line("break;");
            Close();
        }
        Line("default:");
        _indent++;
        Line("throw new global::AvroCodeGen.Runtime.AvroException(\"Invalid union index.\");");
        _indent--;
        Close();
        Line("r.ReadUnionEnd();");
    }
}
